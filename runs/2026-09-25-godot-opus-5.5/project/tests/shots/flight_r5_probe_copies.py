#!/usr/bin/env python3
"""Copies the verifiers' flight probes (tests/probes/flight) into
tests/shots/flight_r5_probes/ with their output paths moved under
artifacts/flight/verify/r5_builder/<round>/, so re-running them on the fixed
code never overwrites the verifiers' own evidence (fix round 5: a first
re-run of r5x did, and its text output was restored from the verifier's run
log). The copies are regenerated, never edited by hand.

  python3 tests/shots/flight_r5_probe_copies.py
  tools/gd.sh flight --headless res://tests/runner.tscn -- --dir=res://tests/shots/flight_r5_probes --suite=r5x_experience
"""
import os, re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = root / "tests/probes/flight"
dst = root / "tests/shots/flight_r5_probes"
dst.mkdir(parents=True, exist_ok=True)
names = ["r3_experience_probe_test.gd", "r4x_experience_probe_test.gd", "r4eng_probe_test.gd",
         "r5x_experience_probe_test.gd", "r5eng_probe_test.gd"]
for n in names:
    s = (src / n).read_text()
    s = re.sub(r'"verify/(r3|r4exp|r4eng|r5exp|r5eng)/', r'"verify/r5_builder/\1/', s)
    s = s.replace('[flight-verify]', '[flight-verify-copy]')
    (dst / n).write_text("# GENERATED by tests/shots/flight_r5_probe_copies.py from tests/probes/flight/%s\n# (outputs moved under artifacts/flight/verify/r5_builder/). Do not edit.\n" % n + s)
    print("[flight] copied", n)
